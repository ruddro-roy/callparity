def _engine(db: Path):
    return create_engine(f"sqlite+pysqlite:///{db}", future=True)


def _schema(engine) -> dict:
    """Dialect-agnostic dump: tables, columns, pks, unique cols, non-unique indexes."""
    insp = inspect(engine)
    out: dict = {}
    for name in sorted(insp.get_table_names()):
        if name == "alembic_version":
            continue
        cols = []
        for col in insp.get_columns(name):
            cols.append(
                {
                    "name": col["name"],
                    "type": type(col["type"]).__name__,
                    "nullable": col["nullable"],
                }
            )
        pk = list(insp.get_pk_constraint(name).get("constrained_columns") or [])
        unique: set[tuple] = set()
        nonunique: set[tuple] = set()
        for ix in insp.get_indexes(name):
            key = tuple(ix["column_names"])
            if ix["unique"]:
                unique.add(key)
            else:
                nonunique.add(key)
        for uq in insp.get_unique_constraints(name):
            unique.add(tuple(uq["column_names"]))
        out[name] = {
            "cols": cols,
            "pk": pk,
            "unique": sorted(unique),
            "indexes": sorted(nonunique),
        }
    return out


