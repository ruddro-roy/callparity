def test_prepare_schema_sqlite_uses_create_all(isolated):
    prepare_schema()
    engine = _engine(isolated)
    names = set(inspect(engine).get_table_names())
    engine.dispose()
    assert EXPECTED_TABLES <= names
    assert "alembic_version" not in names


def test_migration_schema_matches_create_all(tmp_path, monkeypatch):
    created = tmp_path / "create_all.db"
    migrated = tmp_path / "migrated.db"

    created_engine = create_engine(f"sqlite+pysqlite:///{created}", future=True)
    Base.metadata.create_all(bind=created_engine)
    created_schema = _schema(created_engine)
    created_engine.dispose()

    monkeypatch.setenv("DATABASE_URL", f"sqlite+pysqlite:///{migrated}")
    get_settings.cache_clear()
    reset_engine()
    assert apply_migrations() == "upgrade"
    migrate_engine = _engine(migrated)
    migrated_schema = _schema(migrate_engine)
    with migrate_engine.connect() as conn:
        version = conn.execute(text("SELECT version_num FROM alembic_version")).scalar()
    migrate_engine.dispose()
    reset_engine()
    get_settings.cache_clear()

    assert created_schema == migrated_schema
    assert version
    assert set(migrated_schema) == EXPECTED_TABLES


