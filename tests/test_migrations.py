def test_apply_migrations_stamps_complete_create_all_schema(isolated):
    init_db()
    assert apply_migrations() == "stamp"
    assert apply_migrations() == "upgrade"
    engine = _engine(isolated)
    names = set(inspect(engine).get_table_names())
    with engine.connect() as conn:
        tickets = conn.execute(text("SELECT count(*) FROM tickets")).scalar()
    engine.dispose()
    assert "alembic_version" in names
    assert EXPECTED_TABLES <= names
    assert tickets == 0


def test_apply_migrations_is_idempotent(isolated):
    assert apply_migrations() == "upgrade"
    assert apply_migrations() == "upgrade"
    engine = _engine(isolated)
    assert set(inspect(engine).get_table_names()) - {"alembic_version"} == EXPECTED_TABLES
    engine.dispose()


def test_apply_migrations_rejects_partial_schema(isolated):
    engine = _engine(isolated)
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE tickets (id VARCHAR(64) PRIMARY KEY)"))
    engine.dispose()
    with pytest.raises(RuntimeError, match="partial schema"):
        apply_migrations()


